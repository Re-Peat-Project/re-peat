class Icesat2(Step):
    name = "icesat2"

    def applies(self, c):
        return "" if any(not (c.kc["dems"].get(d) or {}).get("skip") for d in ("deltadtm", "demnas")) else "no DeltaDTM / DEMNAS variant"

    def done(self, c):
        return c.icesat2() is not None

    def commands(self, c):
        t0, t1 = c.st["dem_correction"]["icesat2_period"]                 # into the data folder; local_inputs copies it into 00_inputs
        return [("main", ["-m", "repeat_common.fetch_icesat2", "--khg", c.name, "--t0", t0, "--t1", t1, str(c.s.data)], HUB)]


class LocalInputs(Step):
    """The KHG's own copies of every nationwide input (pipeline/localize.py), so the folder runs without the data folder."""
    name = "local_inputs"

    def done(self, c):
        return (c.kf / "00_inputs" / "local_manifest.csv").is_file()

    def commands(self, c):
        code = ("import sys; sys.path.insert(0, r'%s'); from pipeline.steps import run_localize; run_localize(r'%s')" % (HUB / "tools", c.code))
        return [("main", ["-c", code], HUB)]


def run_localize(code: str) -> None:
    from .config import load
    from . import khgconf, localize
    s = load()
    kc = khgconf.load(s, code)
    c = Ctx(s, kc)
    sit = s.get("environment", {}).get("SITMAT_PROCESSED")
    out = localize.localize(s.data, c.kf, (kc.get("peat_depth") or {}).get("path"), c.icesat2(), Path(sit) if sit else None)
    print(f"wrote {out}")


class DemCorrection(Step):
    name, per_dem, env = "dem_correction", True, "dem"

    def applies(self, c):
        return "LiDAR is used as delivered" if c.dem == "lidar" else super().applies(c)

    def done(self, c):
        return c.surface() is not None

    def commands(self, c):
        tpl = HUB / c.st["dem_correction"]["templates"].format(dem=c.dem)
        out = c.kf / "01_dem" / "processed" / c.dem
        ground = c.icesat2()
        if ground is None:
            raise SystemExit("no ICESat-2 points (run the icesat2 step)")
        text = tpl.read_text(encoding="utf-8")
        vals = {"{dem}": c.t(c.variant()["clip"]), "{aoi}": c.t(c.kf / "00_inputs" / "khg.gpkg"), "{out}": c.t(out), "{ground_points}": c.t(ground)}
        for k, v in vals.items():
            text = text.replace(k, v)
        tracked = c.site / c.dem / "dem_correction.yaml"
        tracked.parent.mkdir(parents=True, exist_ok=True)
        tracked.write_text(GEN.format(f=c.fname) + text, encoding="utf-8")
        run = out / "config.yaml"                         # tiled_dtm.py does not expand ${...}
        out.mkdir(parents=True, exist_ok=True)
        run.write_text(expand(text, {"REPEAT_KHG": str(c.s.khg_root), "REPEAT_DATA": str(c.s.data)}), encoding="utf-8")
        return [("dem", ["script/tiled_dtm.py", "--config", str(run)], c.s.ws / "repeat-dem")]


class Delineation(Step):
    name, per_dem, env = "delineation", True, "delineation"

    def done(self, c):
        return (c.sd("02_delineation") / "subkhg_units.gpkg").is_file()

    def config(self, c) -> Path:
        surf = c.surface()
        if surf is None:
            raise SystemExit(f"no {c.dem} surface (run dem_correction)")
        d = c.st["delineation"]
        f = c.fname
        body = {"khg": f"${{REPEAT_KHG}}/{f}/00_inputs/khg.gpkg", "khg_id_field": "khg_id", "cache_dir": f"${{REPEAT_KHG}}/{f}/cache/delineation_{c.dem}",
                "out": c.t(c.sd("02_delineation")), "rasters": {"dtm": c.t(surf)},
                "vectors": {"canals": f"${{REPEAT_KHG}}/{f}/00_inputs/canals.gpkg", "rivers": f"${{REPEAT_KHG}}/{f}/00_inputs/rivers.gpkg"},
                "units": {"subkhg": {"canal_class_field": c.kc["canals"]["class_field"], "outlet_canal_classes": d["outlet_canal_classes"],
                                     "min_area_km2": d["min_area_km2"], "merge": d["merge"]}}}
        return _write(c.site / c.dem / "delineate.yaml", GEN.format(f=f) + f"# {c.name}, DEM {c.dem}: sub-KHG delineation (repeat-delineation).\n", body)

    def commands(self, c):
        return [("delineation", ["-m", "repeat_delineation", "--config", str(self.config(c))], c.s.ws / "repeat-delineation")]


