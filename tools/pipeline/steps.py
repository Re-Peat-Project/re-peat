class Deficit(Step):
    name = "deficit"
    optional = True             # needs SiTMAT stations inside the KHG (concessions only); without them the chain runs without a deficit

    def applies(self, c):
        return "" if c.first_dem() else "no DEM variant"

    def note(self, c) -> Path:
        return c.kf / "03_neraca" / "runs" / "deficit" / "NOT_AVAILABLE.txt"

    def done(self, c):
        return (c.kf / "03_neraca" / "runs" / "deficit" / "neraca_khg.csv").is_file() or self.note(c).is_file()

    def config(self, c) -> Path:
        d0 = c.first_dem()
        c0 = Ctx(c.s, c.kc, d0)
        surf = c0.surface()
        if surf is None or not (c0.sd("02_delineation") / "subkhg_units.gpkg").is_file():
            raise SystemExit(f"the deficit is set up on the {d0} variant: run its dem_correction and delineation first")
        n, f = c.st["neraca"], c.fname
        cls = c.kc["canals"]["class_field"]
        body = {"name": f.split("_", 1)[1], "khg_id": c.code, "khg": f"${{REPEAT_KHG}}/{f}/00_inputs/khg.gpkg", "dtm": c.t(surf),
                **({"peat_depth": {"path": c.t(c.peat_depth()), "scale": c.kc["peat_depth"]["scale"]}} if c.peat_depth() else {}),
                "canals": {"path": f"${{REPEAT_KHG}}/{f}/00_inputs/canals.gpkg", "class_field": cls,
                           "classes": {"primary": ["Kanal Primer"], "secondary": ["Kanal Sekunder"], "tertiary": ["Kanal Tersier"]}},
                "units": c.t(c0.sd("02_delineation") / "subkhg_units.gpkg"), "inputs_dir": f"${{REPEAT_KHG}}/{f}/03_neraca/inputs",
                "forcing_window": "calibration", "evaporation": "E_era5_mm",
                "forcing_direct": {"cache_dir": f"${{REPEAT_KHG}}/{f}/cache/{c.code}/neraca", "start": n["window"][0], "end": n["window"][1],
                                   "tz_hours": TZ.get(c.kc["khg"].get("province"), 7)},
                "stations": {"tma": {"path": c.sitmat()}, "start": n["window"][0], "end": n["window"][1]}}
        return _write(c.site / "neraca.yaml", GEN.format(f=f) + f"# {c.name}: KHG deficit (SiTMAT stations, ERA5); set up on the {d0} variant's units.\n", body)

    def commands(self, c):
        cfg = str(self.config(c))
        out = c.kf / "03_neraca" / "runs" / "deficit"
        return [("main", ["-m", "repeat_neraca.stations", "--config", cfg], HUB),
                ("main", ["-m", "repeat_neraca.run", "--config", cfg, "--tier", "1", "--classes", "primary,secondary,tertiary", "--out", str(out)], HUB)]


class Prioritisation(Step):
    name, per_dem = "prioritisation", True

    def done(self, c):
        return bool(list(c.sd("04_prioritisation").glob("**/unit_prioritas.gpkg")))

    def config(self, c) -> Path:
        surf = c.surface()
        p, f, n = c.st["prioritisation"], c.fname, c.s["national"]
        rasters = {"dtm": c.t(surf)}
        if c.peat_depth():
            rasters["peat_depth"] = c.t(c.peat_depth())
        feg = c.local("feg_protected.gpkg")
        nl_cfg = self.national_layers(c)
        body = {"khg": f"${{REPEAT_KHG}}/{f}/00_inputs/khg.gpkg", "khg_id_field": "khg_id",
                "units": {"mode": "vector", "path": c.t(c.sd("02_delineation") / "subkhg_units.gpkg")}, "years": p["years"],
                "cache_dir": f"${{REPEAT_KHG}}/{f}/cache", "out": c.t(c.sd("04_prioritisation")), "rasters": rasters,
                "params": {"peat_depth_scale": (c.kc.get("peat_depth") or {}).get("scale", 0.01), "ipg_canal_class_field": c.kc["canals"]["class_field"],
                           "ipg_canal_classes": p["ipg_canal_classes"]},
                "vectors": {"canals": f"${{REPEAT_KHG}}/{f}/00_inputs/canals.gpkg", "rivers": f"${{REPEAT_KHG}}/{f}/00_inputs/rivers.gpkg",
                            "blocks": f"${{REPEAT_KHG}}/{f}/00_inputs/blocks.gpkg",
                            "protected": {"path": c.t(feg) if feg else "${REPEAT_DATA}/" + n["protected"]["path"], "field": n["protected"]["field"],
                                          "values": n["protected"]["values"]}},
                "tma": {"path": c.sitmat(), "period": c.st["neraca"]["window"]},
                "sources": {"ndmi": {"res_m": p["ndmi_res_m"]}, "burned": {"enabled": False}, "firms": {"enabled": False}, "deficit": {"enabled": False}},
                "extra_indicators": [c.t(c.sd("03_neraca") / "runs" / "balance" / "neraca_balance_unit.csv")],
                "scoring": {"ranksum_columns": {"u_wb_daily_mean": "p_minus_et_mean_mm"}, "ranksum_weights": {"u_deficit_months": 0}},
                "priority_export": {"neraca_khg": f"${{REPEAT_KHG}}/{f}/03_neraca/runs/deficit/neraca_khg.csv"
                                    if (c.kf / "03_neraca" / "runs" / "deficit" / "neraca_khg.csv").is_file() else None, "design_period_days": None},
                "national_layers": {"config": c.t(nl_cfg)}}
        return _write(c.site / c.dem / "subkhg.yaml", GEN.format(f=f) + f"# {c.name}, DEM {c.dem}: sub-KHG prioritisation (repeat-prioritisation).\n", body)

    def national_layers(self, c) -> Path:
        """The national profile config the national layers read: the shared one, with its data folder set to the KHG's clipped
        copies (00_inputs/national) when they exist."""
        src = Path(c.st["prioritisation"]["national_profile"])
        nat = c.local("national")
        if not nat:
            return src
        cfg = yaml.safe_load(src.read_text(encoding="utf-8"))
        cfg["data"] = c.t(nat)
        peat = cfg.setdefault("peat", {})
        from .localize import NATIONAL_RASTERS
        for k, name in NATIONAL_RASTERS.items():
            peat[k] = c.t(nat / name)
        if cfg.get("tma"):
            cfg["tma"]["path"] = c.sitmat()
        return _write(c.site / "national_layers.yaml", GEN.format(f=c.fname) + f"# {c.name}: the national profile settings of {src.name}, "
                      "reading the KHG's clipped national files (00_inputs/national).\n", cfg)

    def commands(self, c):
        return [("main", ["-m", "repeat_prioritisation.subkhg.run", "--config", str(self.config(c))], c.s.ws / "repeat-prioritisation")]


class Pump(Step):
    name, per_dem, env = "pump", True, "pump"

    def done(self, c):
        return (c.sd("05_pump") / "report.html").is_file()

    def commands(self, c):
        cfg = c.sd("05_pump") / "run_config.yaml"
        # --overwrite: the step runs only when forced or unfinished, and then the config (and its copy of the preset) must
        # come from the current settings; a kept config would rerun with the defaults of its first run
        gen = ["scripts/khg_run_config.py", str(c.kf), "--dem", c.dem, "--dtm", str(c.surface()), "--overwrite"] + \
              (["--tertiary"] if c.st["pump"].get("tertiary") else [])
        run = ["-m", "repeat_pump.cli", "run", "--config", str(cfg), "--accept", "2", "--accept", "6", "--accept", "9"]
        return [("pump", gen, c.s.ws / "repeat-pump"), ("pump", run, c.s.ws / "repeat-pump"),
                ("pump", ["-m", "repeat_pump.cli", "report-html", "--config", str(cfg)], c.s.ws / "repeat-pump")]


