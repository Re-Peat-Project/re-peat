"""The steps of the full chain. Each step says whether it applies to a KHG (and DEM), whether its output is already there, and how to
run it: a list of commands, each (environment, argv, working directory). Configs the modules read are generated here into
re-peat/sites/<folder>/<dem>/ with ${REPEAT_KHG} / ${REPEAT_DATA} paths (tracked, portable); the DEM correction, whose tool does not
expand variables, also gets its expanded copy in the work folder.
"""
from __future__ import annotations

import glob
from pathlib import Path

import yaml

from .config import HUB, Settings, expand

TZ = {"Kalimantan Selatan": 8, "Papua Selatan": 9, "Papua": 9}          # WITA / WIT; the rest of the selected KHG are WIB (7)


class Ctx:
    """One KHG (and DEM) as the steps see it."""

    def __init__(self, s: Settings, kc: dict, dem: str | None = None):
        from repeat_common import khg as K
        self.s, self.kc, self.dem, self.K = s, kc, dem, K
        self.code, self.name, self.fname = kc["khg"]["code"], kc["khg"]["name"], kc["khg"]["folder"]
        self.kf = s.khg_root / self.fname
        self.site = HUB / "sites" / self.fname
        self.st = kc["settings"]

    def sd(self, step: str) -> Path:
        return self.K.step_dir(self.code, step, self.dem)

    def t(self, p) -> str:
        """A path as written in a tracked config: ${REPEAT_KHG}/..., ${REPEAT_DATA}/... or ${REPEAT_HUB}/..."""
        p = str(Path(p))
        for var, root in (("REPEAT_KHG", self.s.khg_root), ("REPEAT_DATA", self.s.data), ("REPEAT_HUB", HUB)):
            r = str(Path(root))
            if p.lower().startswith(r.lower()):
                return "${" + var + "}" + p[len(r):].replace("\\", "/")
        return p.replace("\\", "/")

    def variant(self) -> dict:
        return self.kc["dems"].get(self.dem) or {"skip": "not in khg.yaml"}

    def surface(self) -> Path | None:
        """The DTM of this variant: the LiDAR clip, or the corrected DeltaDTM / DEMNAS."""
        v = self.variant()
        if self.dem == "lidar":
            return Path(v["clip"]) if v.get("clip") and Path(v["clip"]).is_file() else None
        for p in (self.kf / "01_dem" / "processed" / self.dem / "dtm_smooth.tif",
                  self.kf / "01_dem" / "benchmark" / "04_processed" / self.dem / "dtm_smooth.tif"):
            if p.is_file():
                return p
        return None

    def first_dem(self) -> str | None:
        """The variant whose units the KHG-level neraca (the deficit) is set up on: the first that runs."""
        return next((d for d in self.s["dems"]["variants"] if not (self.kc["dems"].get(d) or {}).get("skip")), None)

    def local(self, rel: str) -> Path | None:
        """A file of the KHG's own copies in 00_inputs (local_inputs step), or None."""
        p = self.kf / "00_inputs" / rel
        return p if p.exists() else None

    def peat_depth(self) -> str | None:
        """The peat-depth raster: the KHG's copy when there is one, else the khg.yaml source."""
        loc = self.local("peat_depth.tif")
        return str(loc) if loc else (self.kc.get("peat_depth") or {}).get("path")

    def sitmat(self) -> str:
        loc = self.local("sitmat")
        return self.t(loc) if loc else "${SITMAT_PROCESSED}"

    def icesat2(self) -> Path | None:
        loc = self.local("icesat2_atl08.gpkg")
        if loc:
            return loc
        key = lambda n: self.K.slug(n).replace("_", "")      # fetch_icesat2 drops the spaces inside a name (PulauBengkalis)
        hits = [f for f in glob.glob(str(self.s.data / "icesat2" / "atl08_*.gpkg"))
                if key(Path(f).stem[6:].rsplit("_", 1)[0]) == key(self.name)]
        return Path(hits[0]) if hits else None


def _write(path: Path, header: str, body: dict) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(header + yaml.safe_dump(body, sort_keys=False, allow_unicode=True, width=160), encoding="utf-8")
    return path


GEN = "# Generated by `python tools/khg_pipeline.py` from sites/{f}/khg.yaml and pipeline.yaml; rerunning rewrites it.\n"


class Step:
    name, per_dem, env = "", False, "main"
    optional = False            # a failure is recorded as "not available" (note file) and does not stop the later steps

    def applies(self, c: Ctx) -> str:
        """'' when the step runs for this KHG / DEM, else the reason it does not."""
        return c.variant().get("skip", "") if self.per_dem else ""

    def done(self, c: Ctx) -> bool:
        raise NotImplementedError

    def commands(self, c: Ctx) -> list[tuple[str, list[str], Path]]:
        raise NotImplementedError


class Inputs(Step):
    name = "inputs"

    def done(self, c):
        return all((c.kf / "00_inputs" / f).is_file() for f in ("khg.gpkg", "canals.gpkg", "rivers.gpkg", "blocks.gpkg"))

    def commands(self, c):
        n = c.s["national"]
        b = c.kf / "00_inputs" / "_boundary.gpkg"
        prep = ["-c", "import sys; sys.path.insert(0, r'%s'); from pipeline.steps import write_boundary; write_boundary(r'%s', r'%s')"
                % (HUB / "tools", c.code, b)]
        args = ["-m", "repeat_prioritisation.subkhg.prepare_inputs", "--khg-shp", str(b), "--khg-id", c.code, "--out", str(c.kf / "00_inputs"),
                "--canals", str(c.s.data / n["canals"]["path"]), "--rivers", str(c.s.data / n["rivers"]["path"]),
                "--lakes", str(c.s.data / n["lakes"]["path"]), "--blocks", str(c.s.data / n["blocks"]["path"]), "--blocks-where", n["blocks"]["where"]]
        return [("main", prep, HUB), ("main", args, HUB)]


def write_boundary(code: str, out: str) -> None:
    """The KHG polygon from the national boundary file (by registry code) for prepare_inputs."""
    import geopandas as gpd
    from repeat_common import gee, khg as K
    from repeat_common.fetch_gee_balance import khg_unit
    from .config import load
    s = load()
    b = gpd.read_file(s.data / s["national"]["boundary"]["path"], layer=gee.BOUNDARY[1])
    u = khg_unit(b, gee.BOUNDARY[2], K.lookup(code))
    if u.empty:
        raise SystemExit(f"{code} not in the boundary file")
    Path(out).parent.mkdir(parents=True, exist_ok=True)
    u.to_file(out, driver="GPKG")


