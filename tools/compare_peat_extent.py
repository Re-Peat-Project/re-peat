"""KLH's peat extent (PPEG LAHAN_GAMB, the project's peat basis) against the KLH 2025 peat map (SiTMAT) and the GFW composite.

    python re-peat/tools/compare_peat_extent.py

Needs `repeat-national-ppeg --layers` (the dissolved PPEG peat extent and the skeg layer) and the national profile outputs
(land_summary.csv for GFW peat per KHG, fire_landstatus/area.parquet for GFW peat per province on the 30 m grid).
Writes re-peat/reports/investigations/peat_extent_comparison.md and peat_extent_khg.csv.

Areas: PPEG from its LUAS_HA; SiTMAT polygons on the equal-area EPSG:6933; GFW as in the national outputs (30 m grid cells).
Also checks the Papua block that PPEG codes NON KHG in its peat, SKEG and FEG fields (fill village "Atabar"): how much
peat SiTMAT and GFW map there.
"""
import os
import re
from pathlib import Path

import geopandas as gpd
import numpy as np
import pandas as pd
import rasterio
from rasterio.mask import mask as rmask

HUB = Path(__file__).resolve().parents[1]
WS = HUB.parent
DATA = Path(os.environ.get("REPEAT_DATA", WS / "_data"))
WORK = Path(os.environ.get("REPEAT_WORK", HUB / "reports"))
NP = WORK / "national_profile"
OUT = HUB / "reports" / "investigations"
EA = "EPSG:6933"


def norm(s):
    return re.sub(r"\s+", " ", str(s)).strip().lower()


def main():
    reg = pd.read_csv(HUB / "sites" / "khg_registry.csv")
    code = dict(zip(reg["name"].map(norm), reg["khg_code"]))
    ppeg = pd.read_csv(NP / "ppeg" / "ppeg_khg.csv")
    ppeg = ppeg[ppeg["khg_name"] != "NON KHG"].assign(k=lambda d: d["khg_name"].map(norm))

    # SiTMAT KLH peat map 2025: peat polygons, overlaid with the KHG boundaries
    sit = gpd.read_file(DATA / "peat" / "lahan_gambut_indonesia_2025.gpkg", layer="lahan_gambut")
    print("SiTMAT LAHAN_GAMB values:", sit["LAHAN_GAMB"].value_counts().to_dict(), flush=True)
    sit = sit[sit["LAHAN_GAMB"].str.contains("Gambut", case=False) & ~sit["LAHAN_GAMB"].str.contains("Non", case=False)].to_crs(EA)
    sit["geometry"] = sit.geometry.make_valid()
    khg = gpd.read_file(DATA / "batas_khg_indonesia.gpkg").to_crs(EA)
    namecol = next(c for c in khg.columns if "nama" in c.lower() or c.lower() in ("khg", "name"))
    khg["k"] = khg[namecol].map(norm)
    ov = gpd.overlay(sit[["PROV_2023", "geometry"]], khg[["k", "geometry"]], how="intersection", keep_geom_type=True)
    sit_khg = (ov.area / 1e4).groupby(ov["k"]).sum()
    sit_prov = (sit.area / 1e4).groupby(sit["PROV_2023"]).sum()

    # GFW per KHG (national profile) and per province (fire tally grid)
    land = pd.read_csv(NP / "land" / "land_summary.csv")
    gfw_khg = land[land["layer"] == "forest"].groupby(land["khg"].map(norm))["peat_km2"].sum() * 100
    area = pd.read_parquet(NP / "fire_landstatus" / "area.parquet", columns=["province", "peat", "area_ha"])
    gfw_prov = area[area["peat"] == 1].groupby("province")["area_ha"].sum()

    # PPEG per province from the attributes
    import pyogrio
    a = pyogrio.read_dataframe(DATA / "ALL_Analysis_Integrasi_Tematik__PPEG_Indonesia__April_2026.gpkg", read_geometry=False,
                               columns=["PROV_2023", "LAHAN_GAMB", "LUAS_HA"], use_arrow=True)
    ppeg_prov = a[a["LAHAN_GAMB"] == "LAHAN GAMBUT"].groupby("PROV_2023")["LUAS_HA"].sum()

    t = ppeg.set_index("k")[["khg_name", "khg_code", "island", "peat_ha"]].rename(columns={"peat_ha": "ppeg_ha"})
    t["sitmat_ha"] = sit_khg.reindex(t.index).fillna(0)
    t["gfw_ha"] = gfw_khg.reindex(t.index)
    t.to_csv(OUT / "peat_extent_khg.csv", index=False, float_format="%.1f")

    # Papua fill block
    sk = gpd.read_file(NP / "ppeg" / "ppeg_layers.gpkg", layer="skeg")
    blk = sk[(sk["skeg"] == "no data") & (sk["khg"] != "NON KHG")]
    blk_ea = blk.to_crs(EA)
    blk_ha = blk["LUAS_HA"].sum()
    sit_in_blk = gpd.overlay(sit[["geometry"]], blk_ea[["geometry"]], how="intersection", keep_geom_type=True).area.sum() / 1e4
    with rasterio.open(DATA / "peat_extent_gfw_v20230315_z11.tif") as r:
        g = blk.to_crs(r.crs)
        arr, tr = rmask(r, g.geometry, crop=True, filled=True, nodata=0)
        # true cell area in ha per row of the Web Mercator raster: nominal area x cos^2(latitude)
        y = tr.f + tr.e * (np.arange(arr.shape[1]) + 0.5)
        lat = 2 * np.arctan(np.exp(y / 6378137.0)) - np.pi / 2
        cell = abs(tr.a * tr.e) * np.cos(lat) ** 2 / 1e4
        gfw_in_blk = float(((arr[0] == 1) * cell[:, None]).sum())

    md = ["# Peat extent: KLH PPEG against the KLH 2025 map (SiTMAT) and the GFW composite", "",
          "Generated by `re-peat/tools/compare_peat_extent.py`. Per KHG: `peat_extent_khg.csv`.", "",
          "## Indonesia (million ha)", "", "| PPEG LAHAN_GAMB | SiTMAT 2025 | GFW composite (30 m grid) |", "|---|---|---|",
          f"| {ppeg_prov.sum() / 1e6:.2f} | {sit_prov.sum() / 1e6:.2f} | {gfw_prov.sum() / 1e6:.2f} |", "",
          "## By province (thousand ha)", "", "| Province | PPEG | SiTMAT 2025 | GFW |", "|---|---|---|---|"]
    pv = pd.concat({"ppeg": ppeg_prov, "sit": sit_prov, "gfw": gfw_prov}, axis=1).fillna(0).sort_values("ppeg", ascending=False)
    md += [f"| {p} | {r['ppeg'] / 1e3:,.0f} | {r['sit'] / 1e3:,.0f} | {r['gfw'] / 1e3:,.0f} |" for p, r in pv.iterrows() if r.max() > 1000]
    both = t.dropna(subset=["gfw_ha"])
    rel = lambda x, y: (x - y).abs() / y.where(y > 0)
    md += ["", "## By KHG", "",
           f"{len(t)} KHG. Peat in PPEG {t['ppeg_ha'].sum() / 1e6:.2f} million ha, SiTMAT {t['sitmat_ha'].sum() / 1e6:.2f}, GFW {both['gfw_ha'].sum() / 1e6:.2f}.", "",
           "| Pair | KHG compared | Median difference | KHG differing by more than 20% | KHG with peat in one and none in the other |", "|---|---|---|---|---|"]
    for name, x, y in [("PPEG vs SiTMAT", t["ppeg_ha"], t["sitmat_ha"]), ("PPEG vs GFW", both["ppeg_ha"], both["gfw_ha"])]:
        r = rel(x, y)
        md.append(f"| {name} | {len(x)} | {r.median() * 100:.1f}% | {(r > .2).sum()} | {((x > 0) != (y > 0)).sum()} |")
    md += ["", "## Papua block coded NON KHG in the PPEG peat fields", "",
           f"{len(blk)} KHG pieces, {blk_ha / 1e6:.2f} million ha (PPEG LUAS_HA), carry no SKEG, FEG or peat-thickness class and LAHAN_GAMB = NON LAHAN GAMBUT. "
           f"SiTMAT 2025 maps {sit_in_blk / 1e6:.2f} million ha of peat there and GFW {gfw_in_blk / 1e6:.2f} million ha.", ""]
    (OUT / "peat_extent_comparison.md").write_text("\n".join(md), encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
