"""Inventory of KLH's integrated thematic analysis for peat ecosystem restoration (PPEG), April 2026.

    python re-peat/tools/inventory_ppeg_integrasi.py [GPKG]

GPKG defaults to $REPEAT_DATA (then ../_data)/ALL_Analysis_Integrasi_Tematik__PPEG_Indonesia__April_2026.gpkg.
Reads the attributes only (no geometry) and writes, in re-peat/reports/investigations/:
  ppeg_integrasi_tematik_values.csv  one row per field and value: polygons and LUAS_HA
  ppeg_integrasi_tematik.md          fields, value areas, consistency checks and the cross-tabulations used so far
Areas are the file's own LUAS_HA (hectares, as delivered); nothing is recomputed from geometry.
"""
import os
import sys
from pathlib import Path

import pandas as pd
import pyogrio

HUB = Path(__file__).resolve().parents[1]
DATA = Path(os.environ.get("REPEAT_DATA", HUB.parent / "_data"))
NAME = "ALL_Analysis_Integrasi_Tematik__PPEG_Indonesia__April_2026.gpkg"
OUT = HUB / "reports" / "investigations"
SKIP = {"OBJECTID", "LUAS_HA", "Shape_Length", "Shape_Area"}
MAX_LISTED = 30          # fields with more values are summarised by their largest values in the Markdown


def mha(x):
    return f"{x / 1e6:,.3f}"


def table(df, index_name):
    rows = [f"| {index_name} | " + " | ".join(map(str, df.columns)) + " |", "|---" * (len(df.columns) + 1) + "|"]
    rows += [f"| {i} | " + " | ".join(v if isinstance(v, str) else f"{v:,.3f}" for v in r) + " |" for i, r in zip(df.index, df.values)]
    return "\n".join(rows)


def show(v):
    return {"": "(empty)", " ": "(space)"}.get(v, v)


def main(path):
    info = pyogrio.read_info(path)
    layer = pyogrio.list_layers(path)[0][0]
    df = pyogrio.read_dataframe(path, read_geometry=False, use_arrow=True)
    total = df["LUAS_HA"].sum()

    vals = []
    for c in df.columns:
        if c in SKIP:
            continue
        g = df.groupby(c, dropna=False)["LUAS_HA"].agg(polygons="size", ha="sum").reset_index().rename(columns={c: "value"})
        g.insert(0, "field", c)
        vals.append(g.sort_values("ha", ascending=False))
    vals = pd.concat(vals, ignore_index=True)
    OUT.mkdir(parents=True, exist_ok=True)
    vals.to_csv(OUT / "ppeg_integrasi_tematik_values.csv", index=False)

    md = [f"# PPEG integrated thematic analysis (KLH, April 2026): inventory",
          "",
          f"Generated by `re-peat/tools/inventory_ppeg_integrasi.py` from `_data/{path.name}` (attributes only). "
          f"All values per field: `ppeg_integrasi_tematik_values.csv`.",
          "",
          f"- Layer `{layer}`: {info['features']:,} {info['geometry_type']} features, {info['crs']}, "
          f"extent {', '.join(f'{v:.3f}' for v in info['total_bounds'])}; {path.stat().st_size / 1e9:.2f} GB.",
          f"- Sum of LUAS_HA: {mha(total)} million ha. "
          f"Of that, {mha(df.loc[df['CD_KHG'] == 'Areal KHG', 'LUAS_HA'].sum())} million ha in KHG "
          f"({df.loc[df['CD_KHG'] == 'Areal KHG', 'NAMA_KHG'].nunique()} KHG names) and "
          f"{mha(df.loc[df['CD_KHG'] != 'Areal KHG', 'LUAS_HA'].sum())} million ha outside (NON KHG).",
          f"- LAHAN_GAMB = LAHAN GAMBUT: {mha(df.loc[df['LAHAN_GAMB'] == 'LAHAN GAMBUT', 'LUAS_HA'].sum())} million ha.",
          "",
          "## Fields",
          "",
          "Each field with its values, number of polygons and area (million ha, LUAS_HA). "
          f"Fields with more than {MAX_LISTED} values show the ten largest.",
          ""]
    for c, g in vals.groupby("field", sort=False):
        n = len(g)
        md.append(f"### {c} ({n} values)")
        md.append("")
        gg = g if n <= MAX_LISTED else g.head(10)
        md.append("| Value | Polygons | Million ha |\n|---|---|---|")
        md += [f"| {show(v)} | {p:,} | {mha(h)} |" for v, p, h in zip(gg["value"], gg["polygons"], gg["ha"])]
        md.append("")

    # consistency checks: blanks and spelling variants
    md += ["## Consistency", ""]
    for c in df.columns:
        if c in SKIP or df[c].dtype.kind in "if":
            continue
        s = df[c].astype(str)
        blanks = {show(b): int((s == b).sum()) for b in ("", " ") if (s == b).any()}
        norm = s.str.lower().str.replace(",", ".", regex=False).str.replace(r"\s+", " ", regex=True).str.strip()
        variants = s.groupby(norm).nunique()
        variants = variants[(variants > 1) & (variants.index != "")]
        if blanks or len(variants):
            parts = []
            if blanks:
                parts.append("blank codes " + ", ".join(f"{k}: {v:,} polygons" for k, v in blanks.items()))
            if len(variants):
                parts.append(f"{len(variants)} values spelt more than one way (case or decimal comma), e.g. "
                             + "; ".join(" / ".join(sorted(s[norm == k].unique())) for k in variants.index[:3]))
            md.append(f"- `{c}`: " + "; ".join(parts) + ".")
    odd = df[(df["CD_KHG"] == "Areal KHG") & (df["CD_SKEG_24"] == "NON KHG")]
    if len(odd):
        vil = odd.groupby(["DESA_2023", "KEC_2023", "KABKO_2023"])["LUAS_HA"].agg(["size", "sum"]).sort_values("sum").iloc[-1]
        md.append(f"- {len(odd):,} polygons ({mha(odd['LUAS_HA'].sum())} million ha) in {odd['NAMA_KHG'].nunique()} KHG "
                  f"({', '.join(sorted(odd['PULAU'].unique()))}) are in a KHG by CD_KHG but NON KHG in CD_SKEG_24 and the peat fields; "
                  f"{int(vil['size']):,} of them carry the village {' / '.join(vil.name)}.")
    md.append("")

    # cross-tabulations
    def xt(r, c, sel=None):
        d = df if sel is None else df[sel]
        return pd.crosstab(d[r], d[c], values=d["LUAS_HA"], aggfunc="sum").fillna(0) / 1e6

    khg = df["CD_KHG"] == "Areal KHG"
    md += ["## Cross-tabulations (million ha)", "",
           "### Actor (PROG_DMPG_2025) by concession, 5 km buffer and forest area status", "",
           table(xt("PROG_DMPG_2025", "CD_KAWASAN").join(xt("PROG_DMPG_2025", "BUFFER")), "PROG_DMPG_2025"), "",
           "### Intervention class (PROG_INTERVENSI) by actor", "",
           table(xt("PROG_INTERVENSI", "PROG_DMPG_2025"), "PROG_INTERVENSI"), "",
           "### Landform (LANDFORM) on peat (LAHAN_GAMB = LAHAN GAMBUT), case-folded", "",
           table((df[df["LAHAN_GAMB"] == "LAHAN GAMBUT"].assign(LANDFORM=lambda d: d["LANDFORM"].str.strip().str.lower().replace({"": "(blank)", "deresi aluvial": "depresi aluvial"}))
                  .groupby("LANDFORM")["LUAS_HA"].sum().sort_values(ascending=False) / 1e6).to_frame("million ha"), "LANDFORM"), "",
           "### Times burned 2015-2024 (BURN_PERIOD) by concession and forest area status, in KHG", "",
           table(xt("BURN_PERIOD", "CD_KONSESI", khg).join(xt("BURN_PERIOD", "CD_KAWASAN", khg), rsuffix=" "), "BURN_PERIOD"), "",
           "### SKEG 2024 damage by burned and canal-affected, in KHG", "",
           table(pd.crosstab(df.loc[khg, "CD_SKEG_24"], [df.loc[khg, "CD_BURN"], df.loc[khg, "CD_ATK"]], values=df.loc[khg, "LUAS_HA"], aggfunc="sum").fillna(0)
                 .pipe(lambda t: t.set_axis([f"{a} / {b}" for a, b in t.columns], axis=1)) / 1e6, "CD_SKEG_24"), ""]

    # the 3.3 million ha / 337 KHG of the FGD TOR: candidate selections
    sel = {
        "SKEG damaged (CD_SKEG_24 Rusak)": df["CD_SKEG_24"].str.startswith("Rusak"),
        "SKEG damaged, on peat (LAHAN_GAMB)": df["CD_SKEG_24"].str.startswith("Rusak") & (df["LAHAN_GAMB"] == "LAHAN GAMBUT"),
        "SKEG damaged, burned or canal-affected": df["CD_SKEG_24"].str.startswith("Rusak") & ((df["CD_BURN"] == "Areal Terbakar") | (df["CD_ATK"] == "Area Terdampak Kanal")),
        "Burned 2015-2024 (CD_BURN)": df["CD_BURN"] == "Areal Terbakar",
        "Burned or canal-affected (PROG_INTERVENSI 01-03)": df["PROG_INTERVENSI"].str[:2].isin(["01", "02", "03"]),
        "Burned and canal-affected (PROG_INTERVENSI 01)": df["PROG_INTERVENSI"].str.startswith("01"),
    }
    md += ["## Candidate selections for the 3.3 million ha in 337 priority KHG", "",
           "The FGD terms of reference (KLH, B.70/E/PKL.4.5/10/2026) state a target of about 3.3 million ha in 337 priority KHG, "
           "chosen on SKEG, in particular burned and canal-affected land. No field in this file flags that target. "
           "The selections below are within KHG.", "",
           "| Selection | Million ha | KHG |", "|---|---|---|"]
    for k, m in sel.items():
        m = m & khg
        md.append(f"| {k} | {mha(df.loc[m, 'LUAS_HA'].sum())} | {df.loc[m, 'NAMA_KHG'].nunique()} |")
    md.append("")
    (OUT / "ppeg_integrasi_tematik.md").write_text("\n".join(md), encoding="utf-8")
    print(OUT / "ppeg_integrasi_tematik.md")


if __name__ == "__main__":
    main(Path(sys.argv[1]) if len(sys.argv) > 1 else DATA / NAME)
