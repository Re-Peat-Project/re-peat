"""Create the per-KHG work folders (_khg/<code>_<name>/) and write what each one holds.

    python tools/khg_workspace.py [--khg "KHG ..." ...]

Creates a folder (00_inputs ... 05_pump, cache, logs) for every KHG in sites/selected_khg.csv, for any extra KHG given
with --khg, and for every KHG that already has a folder in sites/ named <code>_<name>. Then writes
- _khg/<code>_<name>/README.md: the KHG (code, province, role), its source data in _data (from sites/khg_data_recap.csv,
  tools/khg_data_recap.py), its DEM inputs (01_dem/inputs/manifest.csv), its tracked configs (sites/<code>_<name>/), and what each step folder holds (files, size, last change);
- _khg/README.md: one row per KHG with the state of each step.
Rerun after any run; it only creates folders and rewrites the README files. The layout and rules: workspace AGENTS.md,
"Per-KHG work folders".
"""
import argparse
import csv
import sys
from datetime import date, datetime
from pathlib import Path

HUB = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(HUB.parent / "repeat-common" / "src"))
from repeat_common import khg  # noqa: E402

STEP_INFO = {"00_inputs": "inputs clipped from _data (subkhg.prepare_inputs)", "01_dem": "DTM work (repeat-dem)",
             "02_delineation": "sub-KHG units (repeat-delineation)", "03_neraca": "neraca air inputs and runs (repeat-neraca)",
             "04_prioritisation": "sub-KHG ranking (repeat-prioritisation subkhg)", "05_pump": "pumping and canal blocks (repeat-pump)",
             "cache": "caches", "logs": "run logs"}


def files_in(p):
    return [f for f in p.rglob("*") if f.is_file()] if p.exists() else []


def describe(p):
    fs = files_in(p)
    if not fs:
        return "empty", "", ""
    size = sum(f.stat().st_size for f in fs)
    last = max(f.stat().st_mtime for f in fs)
    top = sorted({f.relative_to(p).parts[0] for f in fs})
    shown = ", ".join(f"`{t}`" for t in top[:8]) + (f" and {len(top) - 8} more" if len(top) > 8 else "")
    return f"{len(fs)} files, {size / 1e6:,.1f} MB", shown, datetime.fromtimestamp(last).strftime("%Y-%m-%d")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--khg", nargs="*", default=[])
    a = ap.parse_args()
    sel = list(csv.DictReader(open(HUB / "sites" / "selected_khg.csv", encoding="utf-8")))
    entries = [(r["khg_name_in_gpkg"], r["role"], r["province"]) for r in sel if r["khg_name_in_gpkg"]]
    unresolved = [r for r in sel if not r["khg_name_in_gpkg"]]
    names = {khg.folder_name(n) for n, _, _ in entries}
    for n in a.khg:
        entries.append((n, "extra", khg.lookup(n)["province"]))
    for d in sorted((HUB / "sites").iterdir()):
        if d.is_dir() and "_" in d.name and d.name.split("_")[0][:1].isdigit():
            code = d.name.split("_")[0]
            r = khg.lookup(code)
            if khg.folder_name(code) not in names | {khg.folder_name(n) for n, _, _ in entries}:
                entries.append((r["name"], "existing site", r["province"]))
    recap = list(csv.DictReader(open(HUB / "sites" / "khg_data_recap.csv", encoding="utf-8"))) if (HUB / "sites" / "khg_data_recap.csv").exists() else []
    index = []
    for name, role, prov in entries:
        r = khg.lookup(name)
        p = khg.folder(name, create=True)
        site = HUB / "sites" / p.name
        L = [f"# {r['name']}", "", f"Code {r['khg_code']}, {r['province']} ({r['kabupaten']}), {int(r['area_ha_kepmen']):,} ha (SK.129/2017). "
             f"Role in RE-PEAT: {role}.", "", f"Generated by `re-peat/tools/khg_workspace.py` on {date.today()}; do not edit, rerun. "
             "Layout and rules: workspace `AGENTS.md`, \"Per-KHG work folders\".", ""]
        L += [f"Tracked configs and runbook: `re-peat/sites/{p.name}/`" if site.exists() else
              f"No tracked configs yet (they go in `re-peat/sites/{p.name}/`).", ""]
        rows = [x for x in recap if khg.norm(x["khg"]) == khg.norm(r["name"])]
        if rows:
            L += ["## Source data in _data", "", "| Theme | Dataset | Resolution (m) | Coverage | Features |", "|---|---|---|---|---|"]
            for x in rows:
                L.append(f"| {x['theme']} | `{x['dataset']}` | {x['res_m']} | {x['coverage_pct'] + '%' if x['coverage_pct'] else ''} | {x['features']} |")
            L += ["", "From `re-peat/sites/khg_data_recap.csv` (`re-peat/tools/khg_data_recap.py`).", ""]
        man = p / "01_dem" / "inputs" / "manifest.csv"
        if man.exists():
            L += ["## DEM inputs, clipped to the KHG", "", "| Product | File | Grid | Cell (m) | Coverage | Height p2 to p98 (m) | Note |", "|---|---|---|---|---|---|---|"]
            for x in csv.DictReader(open(man, encoding="utf-8")):
                z = f"{x['z_p02']} to {x['z_p98']}" if x.get("z_p02") else ""
                L.append(f"| {x['product']} | {'`01_dem/inputs/' + x['file'] + '`' if x['file'] else ''} | {x.get('crs', '')} | {x.get('res_m', '')} | "
                         f"{x['cover_pct'] + '%' if x.get('cover_pct') else ''} | {z} | {x['note']} |")
            L += ["", "From `01_dem/inputs/manifest.csv` (`repeat-dem/script/prepare_khg_dem.py`).", ""]
        L += ["## Work in this folder", "", "| Step | What goes here | Contents | Last change |", "|---|---|---|---|"]
        state = {}
        for s in khg.STEPS:
            size, top, last = describe(p / s)
            state[s] = size != "empty"
            L.append(f"| `{s}/` | {STEP_INFO[s]} | {size}{': ' + top if top else ''} | {last} |")
        (p / "README.md").write_text("\n".join(L) + "\n", encoding="utf-8")
        index.append((p.name, r["name"], role, prov, state))
        print(f"{p.name}: " + " ".join(s[:2] for s in khg.STEPS[:6] if state[s]))
    I = ["# Per-KHG work folders", "", f"Generated by `re-peat/tools/khg_workspace.py` on {date.today()}; do not edit, rerun. "
         "One folder per KHG; layout and rules in the workspace `AGENTS.md`, \"Per-KHG work folders\". ✓ = the step folder holds files.", "",
         "| Folder | KHG | Role | Province | " + " | ".join(s for s in khg.STEPS[:6]) + " |", "|---|---|---|---|" + "---|" * 6]
    for fn, n, role, prov, st in index:
        I.append(f"| [{fn}]({fn}/README.md) | {n} | {role} | {prov} | " + " | ".join("✓" if st[s] else "" for s in khg.STEPS[:6]) + " |")
    if unresolved:
        I += ["", "Not created: " + "; ".join(f"{u['name_as_given']} ({u['match_status']})" for u in unresolved)]
    (khg.root() / "README.md").write_text("\n".join(I) + "\n", encoding="utf-8")
    print("wrote", khg.root() / "README.md")


if __name__ == "__main__":
    main()
